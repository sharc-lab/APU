"""Task BK closeout: one row per CC cell from the copied weekend windows.

Reads derived/cc/windows_20261023_25/<host>_<window>/<label>/ (byte copies of the queue output) and
writes analysis/cc_20261026/cells.json and RUNS.md. A cell's values come from its SEALED tree when
one verifies (tools/seal_verify.py); otherwise from the unsealed tree, labelled UNSEALED.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from tools.seal_verify import verify_seal  # noqa: E402

WIN_ROOT = ROOT / "derived" / "cc" / "windows_20261023_25"
OUT = Path(__file__).resolve().parent
RID = re.compile(r"([0-9a-f]{8})-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}")


def load(p: Path) -> Any:
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def runs_in(cell_dir: Path) -> dict[str, dict[str, Any]]:
    """run_id -> best record (sealed MATCH first, else unsealed) found anywhere under the cell."""
    out: dict[str, dict[str, Any]] = {}
    for summ in sorted(cell_dir.rglob("summary.json")):
        d = summ.parent
        m = RID.search(d.name)
        if not m or "derived__" not in d.name:
            continue
        rid = m.group(1)
        sealed = "sealed_" in d.name
        verdict = verify_seal(d) if sealed else "UNSEALED"
        s = load(summ)
        if not isinstance(s, dict):
            continue
        rec = {
            "run_id": rid,
            "dir": str(d.relative_to(ROOT)),
            "seal": verdict,
            "summary": s,
            "plan": load(d / "plan.json") or {},
            "points_dir": str((d / "points").relative_to(ROOT)),
        }
        prev = out.get(rid)
        rank = 2 if str(verdict).startswith("MATCH") else (1 if not sealed else 0)
        prank = -1 if prev is None else prev["_rank"]
        if rank > prank:
            rec["_rank"] = rank
            out[rid] = rec
    return out


def row(host: str, window: str, label: str, rec: dict[str, Any]) -> dict[str, Any]:
    s = rec["summary"]
    plan = rec["plan"]
    cc = plan.get("cc") or {}
    pts = []
    for p in s.get("points") or []:
        if "n_cached" in p:
            pts.append([int(p["n_cached"]), bool(p.get("holds")), p.get("failure_mode")])
    out = {
        "host": host,
        "window": window,
        "label": label,
        "run_id": rec["run_id"],
        "seal": rec["seal"],
        "dir": rec["dir"],
        "kind": s.get("kind"),
        "arm": s.get("arm"),
        "status": s.get("status"),
        "cc_cell": cc.get("cell"),
        "scheduler": plan.get("scheduler_config"),
        "largest_n_cached": s.get("largest_n_cached"),
        "first_fail_n_cached": s.get("first_fail_n_cached"),
        "points": pts,
        "note": s.get("note"),
    }
    if s.get("kind") in ("cc_grow", "cc_conc"):
        out["largest_holding_step"] = s.get("largest_holding_step")
        out["first_failing_step"] = s.get("first_failing_step")
    return out


def main() -> int:
    rows: list[dict[str, Any]] = []
    for wdir in sorted(p for p in WIN_ROOT.iterdir() if p.is_dir()):
        host, window = wdir.name.split("_", 1)
        cells_txt = (
            (wdir / "cells.txt").read_text(encoding="utf-8")
            if (wdir / "cells.txt").is_file()
            else ""
        )
        for line in cells_txt.splitlines():
            parts = line.split()
            if not parts:
                continue
            label = parts[0]
            rc = next((x[3:] for x in parts if x.startswith("rc=")), "")
            cell_dir = wdir / label
            recs = runs_in(cell_dir) if cell_dir.is_dir() else {}
            if not recs:
                rows.append(
                    {"host": host, "window": window, "label": label, "rc": rc, "run_id": None}
                )
                continue
            for rec in recs.values():
                r = row(host, window, label, rec)
                r["rc"] = rc
                rows.append(r)
        listed = {ln.split()[0] for ln in cells_txt.splitlines() if ln.split()}
        for cell_dir in sorted(p for p in wdir.iterdir() if p.is_dir() and p.name not in listed):
            # a cell whose folder reached the Mac but whose cells.txt line was never written
            # (e.g. the queue stopped on its park step)
            for rec in runs_in(cell_dir).values():
                r = row(host, window, cell_dir.name, rec)
                r["rc"] = "not_in_cells_txt"
                rows.append(r)
    (OUT / "cells.json").write_text(json.dumps(rows, indent=1) + "\n", encoding="ascii")
    lines = [
        "# CC weekend runs (Task BK closeout; generated by analysis/cc_20261026/collect.py)",
        "",
        "Records: derived/cc/windows_20261023_25/ (byte copies of the queue windows; sidecar CSVs",
        "stay in ~/seam_closeout_1013, listed with sha256 in CSV_MANIFEST.sha256). Seal verdicts from",
        "tools/seal_verify.py on the Mac copies.",
        "",
        "| host | window | label | run_id | rc | seal | status | L* (largest held) | first fail |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['host']} | {r['window']} | {r['label']} | {r.get('run_id') or '-'} | "
            f"{r.get('rc', '')} | {r.get('seal', '-')} | {r.get('status', '-')} | "
            f"{r.get('largest_n_cached', r.get('largest_holding_step', '-'))} | "
            f"{r.get('first_fail_n_cached', r.get('first_failing_step', '-'))} |"
        )
    (OUT / "RUNS.md").write_text("\n".join(lines) + "\n", encoding="ascii")
    print(len(rows), "rows")
    return 0


if __name__ == "__main__":
    sys.exit(main())
